# ml_pipeline/reporting.py

"""
Turn reports/*.json into prose: the README results block and reports/EVALUATION.md.

Nothing here computes a metric. Every number is read from a report written by a
pipeline script; a report that does not exist renders as "pending", never as a guess.
The output is deterministic for a given set of reports, so CI can check that the README
and EVALUATION.md are up to date (`--check`).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from app.core.settings import get_settings

REPORTS = ("data_quality", "model_comparison", "upskilling_eval", "salary_eval", "workforce_summary",
           "multilingual_eval", "impact")
START, END = "<!-- results:start -->", "<!-- results:end -->"
STATUS_START, STATUS_END = "<!-- evidence-status:start -->", "<!-- evidence-status:end -->"
MODEL_ORDER = ("b0", "b1", "b2", "b3a", "b3b", "hgt")


def load_reports(reports_dir: Path | None = None) -> dict[str, dict | None]:
    d = reports_dir or get_settings().reports_dir
    out: dict[str, dict | None] = {}
    for name in REPORTS:
        p = d / f"{name}.json"
        out[name] = json.loads(p.read_text(encoding="utf-8")) if p.exists() else None
    return out


# --- formatting ---------------------------------------------------------------------------------

def num(x: Any, digits: int = 0) -> str:
    if x is None:
        return "-"
    return f"{x:,.{digits}f}"


def pct(x: Any, digits: int = 1) -> str:
    return "-" if x is None else f"{x * 100:.{digits}f}%"


def inr(x: Any) -> str:
    if x is None:
        return "-"
    x = float(x)
    if x >= 1e7:
        return f"₹{x / 1e7:.2f} Cr"
    if x >= 1e5:
        return f"₹{x / 1e5:.2f} L"
    return f"₹{x:,.0f}"


def ci(v: Any, digits: int = 3) -> str:
    if not v:
        return ""
    return f" [{v[0]:.{digits}f}, {v[1]:.{digits}f}]"


def table(header: list[str], rows: list[list[str]], align: str | None = None) -> str:
    align = align or "l" + "r" * (len(header) - 1)
    sep = ["---:" if a == "r" else "---" for a in align]
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join(sep) + " |"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def pending(what: str) -> str:
    return f"*Pending:* {what}"


def _stamp(rep: dict | None) -> str:
    if not rep:
        return ""
    p = rep.get("provenance", {})
    git = p.get("git", {})
    commit = (git.get("commit") or "")[:7]
    dirty = " (uncommitted changes)" if git.get("dirty") else ""
    return f"<sub>Generated by `{p.get('script', '?')}` at {p.get('generated_at_utc', '?')} from commit `{commit}`{dirty}.</sub>"


