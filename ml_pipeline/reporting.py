def data_section(dq: dict | None, short: bool = True) -> str:
    title = "### Data (from `reports/data_quality.json`)"
    if not dq:
        return f"{title}\n\n" + pending("cleaning, geography, ESCO linking and NCO mapping statistics.")
    counts = {r["step"]: r["rows"] for r in dq.get("row_counts", []) if isinstance(r, dict) and "step" in r}
    geo, sl, tl, sal, tmp = dq["geography"], dq["skill_linking"], dq["title_linking"], dq["salary"], dq["temporal"]
    tiers = geo.get("jobs_by_primary_tier", {})

    def tier(k: str) -> int | None:
        for key in (k, f"{k}.0"):
            if key in tiers:
                return tiers[key]
        return None

    by_tier = sal.get("by_tier", {})
    gold = dq.get("gold_evaluation", {}).get("skills", {})
    if gold.get("status") == "evaluated":
        gold_txt = (f"{pct(gold['precision_mention_weighted'])}{_ci_pct(gold.get('precision_mention_weighted_ci95'))}"
                    f" precision, {pct(gold.get('recall_mention_weighted'))} recall "
                    f"(mention-weighted, {gold['labelled_test']} held-out labels)")
    else:
        gold_txt = "*pending team labels*"
    rows = [
        ["Raw postings", num(dq["dataset"]["raw_rows"])],
        ["After removing duplicate job IDs", num(dq["final_jobs"])],
    ]
    if "jobs_with_tags" in counts:
        rows.append(["Jobs with at least one skill tag", num(counts["jobs_with_tags"])])
    rows += [
        ["Non-remote jobs resolved to an Indian city",
         f"{pct(geo['city_resolution_rate_excl_remote'])} ({num(geo['distinct_cities'])} cities, "
         f"{geo['distinct_states']} states/UTs)"],
        ["Jobs by primary city tier (1 / 2 / 3)", f"{num(tier('1'))} / {num(tier('2'))} / {num(tier('3'))}"],
        ["Unique skill tags", f"{num(sl['unique_tags'])} ({num(sl['tag_mentions'] / 1000)}K mentions)"],
        ["Tag mentions linked to an ESCO skill", f"{pct(sl['mention_coverage'])} (threshold {sl['threshold']}, "
         f"{'tuned on gold labels' if str(sl.get('threshold_status', '')).startswith('tuned') else 'provisional'})"],
        ["Jobs linked to an ESCO occupation",
         f"{pct(tl['job_coverage'])} ({num(tl['distinct_occupations_used'])} distinct occupations)"],
        ["Postings that disclose salary",
         f"{pct(sal['disclosed_share'])} (Tier 1: {pct(by_tier.get('1', {}).get('salary_disclosed_share'))}, "
         f"Tier 2: {pct(by_tier.get('2', {}).get('salary_disclosed_share'))}, "
         f"Tier 3: {pct(by_tier.get('3', {}).get('salary_disclosed_share'))})"],
        ["Posting dates", f"{'real, from `jobId`' if tmp.get('posting_dates_available') else 'not available'}; "
         f"{pct(tmp.get('share_consistent_within_1_day'))} agree with \"N days ago\"; "
         f"inferred scrape date {tmp.get('inferred_scrape_date')}"],
        ["Skill-linking precision (team-labelled gold)", gold_txt],
    ]
    out = f"{title}\n\n" + table(["", ""], rows, "lr")
    if not short:
        out += "\n\n" + _stamp(dq)
    return out


def _ci_pct(v: Any) -> str:
    return f" [{v[0] * 100:.1f}, {v[1] * 100:.1f}]" if v else ""


def _models(mc: dict) -> list[tuple[str, dict]]:
    ms = mc.get("models", {})
    return [(k, ms[k]) for k in MODEL_ORDER if k in ms] + [(k, v) for k, v in ms.items() if k not in MODEL_ORDER]


def models_section(mc: dict | None, short: bool = True) -> str:
    title = "### Models (from `reports/model_comparison.json`)"
    if not mc:
        return f"{title}\n\n" + pending(
            "T1 job-skill completion, T2 occupation-skill recovery and T3 candidate→job fit for B0 Popularity, "
            "B1 TF-IDF kNN, B2 SkillAlign (mpnet + FAISS), B3a Adamic-Adar, B3b LightGCN and the HGT.")
    rows = []
    for _, m in _models(mc):
        mean = m["mean"]

        def cell(task: str, key: str, _mean=mean) -> str:
            t = _mean.get(task)
            if not t:
                return "n/a"
            return f"{t[key]:.3f}" + ("" if short else ci(t.get(f"{key}_ci95")))

        lat = mean.get("latency", {}).get("jobs_for_profile", {})
        rows.append([m["name"], cell("t1", "ndcg@10"), cell("t2", "ndcg@10"), cell("t3", "recall@10"),
                     cell("t3", "ndcg@10"), cell("t3", "mrr"), num(lat.get("p50_ms"), 1), num(lat.get("p95_ms"), 1),
                     num(mean.get("memory", {}).get("rss_mb"))])
    header = ["Model", "T1 NDCG@10", "T2 NDCG@10", "T3 Recall@10", "T3 NDCG@10", "T3 MRR", "p50 ms", "p95 ms", "RSS MB"]
    comp = mc.get("comparison", {})
    lines = [title, "", table(header, rows)]
    if mc.get("quick_mode"):
        lines += ["", "> Quick mode (subsampled queries): a smoke test, not the final benchmark."]
    if comp:
        lines += ["", f"**Shipped:** {comp.get('winner_name')} ({comp.get('rule')})."]
        hv = comp.get("hgt_vs_best_baseline")
        if hv and "t3" in hv:
            d = hv["t3"]
            verdict = "beats" if comp.get("hgt_beats_best_baseline_on_t3") else "does not beat"
            lines.append(f"The HGT {verdict} the best baseline ({hv['baseline']}) on T3: paired NDCG@10 difference "
                         f"{d['mean_diff']:+.4f}{ci(d.get('ci95'), 4)}.")
    lines += ["", "T1 = hidden half of a held-out job's skills; T2 = hidden 20% of an ESCO occupation's skills; "
                  "T3 = rank ~9.5K unseen pool jobs for a pseudo-candidate. Latency = ranking all pool jobs for one profile."]
    if not short:
        lines += ["", _stamp(mc)]
    return "\n".join(lines)


def upskilling_section(ue: dict | None, short: bool = True) -> str:
    title = "### Upskilling (from `reports/upskilling_eval.json`)"
    if not ue:
        return f"{title}\n\n" + pending(
            "jobs unlocked by lazy greedy, greedy on F and top-k-by-frequency against the exact optimum, "
            "for k ∈ {1, 3, 5} and τ ∈ {0.4, 0.6, 0.8}.")
    grid = ue["grid"]
    keys = ["k=3,tau=0.6"] if short else list(grid)
    names = {"exact_ilp": "Exact (CP-SAT ILP)", "greedy_F": "Greedy on F (shipped with ILP)",
             "lazy_greedy_G": "Lazy greedy on G (1−1/e on G)", "frequency": "Top-k by frequency"}
    out = [title, ""]
    for key in keys:
        g = grid[key]
        rows = []
        for m in ("exact_ilp", "greedy_F", "lazy_greedy_G", "frequency"):
            s = g[m]
            rows.append([names[m], num(s["mean_F"], 2), f"{s['mean_gap_pct']:.2f}%", f"{s['p95_gap_pct']:.2f}%",
                         pct(s["share_optimal"]), num(s["runtime_ms_p50"], 1), num(s["runtime_ms_p95"], 1)])
        k, tau = key.replace("k=", "").split(",tau=")
        out += [f"**k = {k}, τ = {tau}** ({g['instances']} instances; mean optimum {g['mean_optimum']} postings; "
                f"ILP proven optimal in {pct(g['ilp_proven_optimal_share'])})", "",
                table(["Method", "Postings unlocked", "Mean gap", "p95 gap", "Optimal", "p50 ms", "p95 ms"], rows), ""]
    if short:
        worst = max(grid.values(), key=lambda g: g["frequency"]["mean_gap_pct"])
        out.append(f"Across all {len(grid)} (k, τ) cells, the frequency baseline's mean gap to the optimum reaches up to "
                   f"{worst['frequency']['mean_gap_pct']:.1f}%; greedy on F stays within "
                   f"{max(g['greedy_F']['mean_gap_pct'] for g in grid.values()):.2f}%. "
                   "Full grid, salary-weighted and effort-aware results: `reports/EVALUATION.md`.")
    if not short:
        bf = ue.get("ilp_vs_brute_force", {})
        if bf.get("instances_checked"):
            scope = (f" (both restricted to the same {bf['candidate_skills_per_instance']} most-listed candidate skills, "
                     f"k in {{{', '.join(map(str, bf['k_values']))}}})" if "candidate_skills_per_instance" in bf else "")
            out += [f"ILP vs brute-force enumeration{scope}: the ILP matches the enumerated optimum in "
                    f"{bf['ilp_equals_brute_force']} of {bf['instances_checked']} cases.", ""]
        else:
            out += [pending("ILP vs brute-force cross-check."), ""]
        for label, key, methods in [
            ("Salary-weighted (k = 3, τ = 0.6)", "salary_weighted_k3_tau0.6",
             ("exact_ilp", "greedy_F", "lazy_greedy_G", "frequency")),
            ("Effort-aware, budget = 3 (τ = 0.6)", "effort_aware_budget3_tau0.6",
             ("exact_ilp", "budgeted_partial", "budgeted_greedy", "frequency"))]:
            s = ue.get(key)
            if not s:
                continue
            money = "salary" in key
            rows = [[m, inr(s[m]["mean_F"]) if money else num(s[m]["mean_F"], 2), f"{s[m]['mean_gap_pct']:.2f}%",
                     pct(s[m]["share_optimal"]), num(s[m]["runtime_ms_p50"], 1)] for m in methods if m in s]
            out += [f"**{label}**" + (f": {s['effort_note']}" if "effort_note" in s else ""), "",
                    table(["Method", "Mean value", "Mean gap", "Optimal", "p50 ms"], rows), ""]
        out.append(_stamp(ue))
    return "\n".join(out).rstrip()


def salary_section(se: dict | None, short: bool = True) -> str:
    title = "### Salary (from `reports/salary_eval.json`)"
    if not se:
        return f"{title}\n\n" + pending("MAE and MdAPE of P50, interval coverage before and after conformal "
                                        "calibration, and the disclosure-bias verdict.")
    t, b, sb = se["test"], se["baseline"], se["selection_bias"]
    rows = [
        ["Model", se["model"]["type"] + " + " + se["model"]["calibration"].split(" (")[0]],
        ["Held-out postings (disclosed salary)", num(t["n"])],
        ["P50 MAE / MdAPE", f"{inr(t['mae_inr'])} / {t['mdape_pct']:.1f}%"],
        ["Baseline (ISCO sub-major × tier median) MAE / MdAPE", f"{inr(b['mae_inr'])} / {b['mdape_pct']:.1f}%"],
        ["P10-P90 coverage (target 80%): raw → calibrated", f"{pct(t['coverage_raw'])} → {pct(t['coverage_cqr'])}"],
        ["Median interval width (calibrated)", inr(t["median_width_inr_cqr"])],
        ["Disclosure predictable from job features (propensity AUC)", f"{sb['propensity']['auc']:.2f}"],
        ["Shown only when support ≥", f"{se['display_rule']['min_support']} similar disclosed postings"],
    ]
    out = f"{title}\n\n" + table(["", ""], rows, "lr")
    out += ("\n\nSalary is disclosed on only " + pct(sb["disclosed_share"]) + " of postings and disclosure is not random, "
            "so every figure is a range for *postings that disclose pay*, never a point estimate.")
    if not short:
        by = se.get("by_group", {})
        for g, label in (("tier", "City tier"), ("exp_band", "Experience band")):
            if g in by:
                rows = [[str(k), num(v["n"]), inr(v["mae_inr"]), f"{v['mdape_pct']:.1f}%", pct(v["coverage_cqr"]),
                         inr(v["median_width_inr_cqr"])] for k, v in by[g].items()]
                out += f"\n\n**By {label.lower()}**\n\n" + table(
                    [label, "n", "MAE", "MdAPE", "Coverage", "Median width"], rows)
        cat = sb.get("categorical", {})
        rows = [[k, f"{v['chi2']:,.1f}", str(v["dof"]), f"{v['cramers_v']:.3f}"] for k, v in cat.items()]
        rows += [[k, "-", "-", f"SMD {v['smd']:+.3f}, KS {v['ks_stat']:.3f}"] for k, v in sb.get("numeric", {}).items()]
        out += "\n\n**Who discloses salary**\n\n" + table(["Feature", "χ²", "dof", "Cramér's V / effect"], rows)
        out += f"\n\n{sb['propensity']['interpretation']}"
        ipw = sb.get("ipw_sensitivity", {})
        if ipw:
            out += (f"\n\nIPW sensitivity: re-weighting disclosed postings to resemble all postings moves predictions on "
                    f"undisclosed jobs by a median {ipw['median_pct_change_on_undisclosed_jobs']:+.2f}% "
                    f"(test MAE with IPW {inr(ipw['test_mae_inr_ipw'])}). {ipw.get('note', '')}")
        out += "\n\n" + _stamp(se)
    return out


def impact_section(im: dict | None, short: bool = True) -> str:
    title = "### Impact (from `reports/impact.json`)"
    if not im:
        return f"{title}\n\n" + pending("extra eligible postings for Tier-2/3 freshers from a 3-skill optimal plan "
                                        "compared with frequency advice, with every assumption listed.")
    e = im["extra_postings_vs_frequency"]
    rows = [
        ["Tier-2/3 fresher profiles (held-out, pseudo-users)", f"{num(im['users'])} (Tier 2: {im['users_by_tier']['2']}, "
         f"Tier 3: {im['users_by_tier']['3']})"],
        ["Median reachable postings: now → frequency plan → optimal plan",
         f"{num(im['eligible_before_median'])} → {num(im['eligible_after_frequency_median'])} → "
         f"{num(im['eligible_after_optimal_median'])}"],
        ["Extra postings, optimal vs frequency (mean; median [IQR])",
         f"{e['mean']:+.2f}; {e['median']:+.0f} [{e['iqr'][0]:+.0f}, {e['iqr'][1]:+.0f}]"],
        ["Profiles where the optimal plan reaches more postings", pct(im["share_users_with_more_postings"])],
        ["Profiles where it is no worse", pct(im["share_users_no_worse"])],
    ]
    out = f"{title}\n\n" + table(["", ""], rows, "lr")
    a = im["assumptions"]
    out += (f"\n\nAssumptions: k = {a['k']} skills; reachable = {a['eligibility']}; person = {a['person']}; "
            f"pool = {a['pool']}. {a['no_causal_claim'].capitalize()}.")
    if not short:
        out += f"\n\n{im['illustration']['label']} Value: {num(im['illustration']['per_1000_users_extra_reachable_postings'])}."
        out += "\n\n" + _stamp(im)
    return out


def readme_block(r: dict[str, dict | None]) -> str:
    parts = [data_section(r["data_quality"]), models_section(r["model_comparison"]),
             upskilling_section(r["upskilling_eval"]), salary_section(r["salary_eval"]), impact_section(r["impact"])]
    return "\n\n".join(parts)


def evidence_status(r: dict[str, dict | None]) -> str:
    """Which reports exist, and what run they came from. Generated so it cannot drift from reports/."""
    def link(label: str, name: str) -> str:
        return f"[{label}](reports/{name}.json)" if r[name] else label

    def state(*names: str) -> str:
        have = [n for n in names if r[n]]
        return "Available" if len(have) == len(names) else "Pending" if not have else "Partly available"

    gold = (r["data_quality"] or {}).get("gold_evaluation", {}).get("skills", {}).get("status") == "evaluated"
    ml = r["multilingual_eval"]
    ml_done = bool(ml) and any(m.get("cross_lingual", {}).get("status") == "evaluated" for m in ml["models"])
    accuracy = ("Available" if gold and ml_done else
                "Evaluation run; team labels pending" if ml else "Pending labels and evaluation")
    mc = r["model_comparison"]
    rows = [
        [link("Data quality", "data_quality"), state("data_quality"),
         "Cleaning counts, geography, linking coverage, graph counts, stage timing"],
        [link("Salary evaluation", "salary_eval"), state("salary_eval"),
         "Held-out errors, interval coverage, subgroup results, disclosure bias"],
        [link("Workforce summary", "workforce_summary"), state("workforce_summary"),
         "Field assignments, state supply coverage, shortage proxy, tier aggregates"],
        [link("Graph comparison and ablations", "model_comparison"),
         "Available (quick mode: smoke test only)" if mc and mc.get("quick_mode") else state("model_comparison"),
         "Six models on three tasks with intervals, latency and memory; names the served model" if mc
         else "No published winner or comparative latency yet"],
        [f"{link('Upskilling', 'upskilling_eval')} and {link('impact', 'impact')}", state("upskilling_eval", "impact"),
         "Gap to the exact optimum per method, runtime, and the Tier-2/3 fresher estimate with its assumptions"
         if r["upskilling_eval"] and r["impact"] else "No published real-pool optimality gap or impact estimate yet"],
        [link("Gold and multilingual accuracy", "multilingual_eval"), accuracy,
         "Linking precision and recall on team labels" if gold and ml_done
         else "Implementation exists; accuracy is not established until the team labels the frozen samples"],
    ]
    out = table(["Evidence", "Current report set", "What it establishes"], rows, "lll")
    runs = []
    for name in REPORTS:
        if r[name]:
            pv = r[name].get("provenance", {})
            git = pv.get("git", {})
            runs.append((str(pv.get("generated_at_utc", ""))[:10], (git.get("commit") or "")[:7], bool(git.get("dirty"))))
    if runs:
        days = sorted({d for d, _, _ in runs if d})
        commits = sorted({c for _, c, _ in runs if c})
        when = days[0] if len(days) == 1 else f"{days[0]} to {days[-1]}"
        out += ("\n\n**Reading the evidence:** reports record the generating script, timestamp, seed where applicable, "
                f"Git state, and supplied input hashes. The current reports were generated on {when} from "
                f"commit{'s' if len(commits) > 1 else ''} {', '.join(f'`{c}`' for c in commits)}"
                + (", with uncommitted changes in the working tree for at least one run" if any(d for _, _, d in runs) else "")
                + ". They are evidence for those runs, not proof that every later edit has been reevaluated.")
    return out


def render_readme(readme: str, r: dict[str, dict | None]) -> str:
    a, b = readme.index(START), readme.index(END)
    readme = readme[: a + len(START)] + "\n\n" + readme_block(r) + "\n\n" + readme[b:]
    if STATUS_START in readme and STATUS_END in readme:
        a, b = readme.index(STATUS_START), readme.index(STATUS_END)
        readme = readme[: a + len(STATUS_START)] + "\n\n" + evidence_status(r) + "\n\n" + readme[b:]
    return readme


