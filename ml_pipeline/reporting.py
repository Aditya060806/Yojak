def _linking_eval(dq: dict | None, ml: dict | None) -> str:
    out = ["## 2. Linking to ESCO", ""]
    if not dq:
        return "\n".join(out + [pending("data_quality.json")])
    sl, tl = dq["skill_linking"], dq["title_linking"]
    rows = [[str(k), pct(v["unique"]), pct(v["mentions"])] for k, v in sl.get("coverage_by_threshold", {}).items()]
    out += [f"Skills: {sl['model']}, threshold {sl['threshold']} ({sl['threshold_status']}); single-word tags must "
            "clear a stricter threshold because generic words (\"development\", \"sales\") otherwise land on unrelated "
            "ESCO skills.", "", "Coverage by threshold (share of unique tags / tag mentions linked):", "",
            table(["Threshold", "Unique tags", "Mentions"], rows), "",
            f"Titles: {pct(tl['job_coverage'])} of jobs linked to an ESCO occupation "
            f"({num(tl['distinct_occupations_used'])} occupations); skill-aware re-ranking changed "
            f"{pct(tl['rerank_changed_share'])} of links (never overriding an exact title match).", ""]
    gold = dq.get("gold_evaluation", {})
    for key, label in (("skills", "Skill links"), ("titles", "Title links")):
        g = gold.get(key, {})
        if g.get("status") == "evaluated":
            p = g.get("precision_mention_weighted", g.get("precision_weighted"))
            r_ = g.get("recall_mention_weighted", g.get("recall_weighted"))
            out.append(f"- **{label}, gold precision:** {pct(p)}{_ci_pct(g.get('precision_mention_weighted_ci95'))}, "
                       f"recall {pct(r_)} on {g.get('labelled_test')} held-out team labels ({g.get('method')}).")
        else:
            out.append(f"- **{label}, gold precision:** {g.get('status', 'pending team labels')}. The frozen stratified "
                       "sample is in `data/gold/`; the team labels it in `/admin/labelling`.")
    out += ["", "### Multilingual input", ""]
    if not ml:
        out.append(pending("reports/multilingual_eval.json"))
    else:
        for m in ml["models"]:
            en, cl = m.get("english", {}), m.get("cross_lingual", {})
            line = f"- `{m['model']}`: English "
            line += (f"precision {pct(en['precision_mention_weighted'])}, recall {pct(en['recall_mention_weighted'])}"
                     if en.get("status") == "evaluated" else en.get("status", "pending"))
            if cl.get("status") == "evaluated":
                line += "; " + "; ".join(f"{v['language']}: top-1 {pct(v['top1_accuracy'])}, recall@5 {pct(v['recall_at_5'])}"
                                         f" (n={v['n']})" for v in cl["per_language"].values())
            else:
                line += f"; cross-lingual {cl.get('status', 'pending')}"
            out.append(line)
        out += ["", f"Decision rule: {ml['decision_rule']}", "", _stamp(ml)]
    return "\n".join(out)


def _models_eval(mc: dict | None) -> str:
    out = ["## 3. Link prediction", ""]
    if not mc:
        return "\n".join(out + [pending("reports/model_comparison.json")])
    d = mc.get("data", {})
    out += ["### Protocol", "", "```", mc.get("protocol", ""), "```", "",
            "Leakage checks (asserted before any model runs): "
            f"hidden job-skill edges visible to models = {d.get('hidden_edges_in_known')}, "
            f"hidden occupation-skill edges visible = {d.get('occ_hidden_edges_in_known')}, "
            f"near-duplicate groups spanning splits = {d.get('groups_spanning_splits')}, "
            f"T3 sources all in the unseen pool = {d.get('t3_sources_all_in_pool')}. "
            f"All model selection used {num(d.get('t3_dev_queries_from_train'))} dev queries built from train jobs.", "",
            "### Results (95% bootstrap CIs; stochastic models: mean of seeds)", "",
            models_section(mc, short=False).split("\n", 2)[2], ""]
    ab = mc.get("ablations", {})
    if ab.get("without_skill_linking"):
        w = ab["without_skill_linking"]
        full = mc["models"]
        rows = [[v["name"], f"{v['t3']['ndcg@10']:.3f}",
                 f"{full[k]['mean']['t3']['ndcg@10']:.3f}" if k in full and "t3" in full[k]["mean"] else "-"]
                for k, v in w["models"].items()]
        out += ["### Ablation: does ESCO linking help?", "", w["note"], "",
                table(["Model", "T3 NDCG@10, raw tags", "T3 NDCG@10, ESCO skills"], rows), ""]
    if ab.get("hgt_variants"):
        base = mc["models"].get("hgt", {}).get("mean", {})
        rows = [["HGT (full)"] + [f"{base[t]['ndcg@10']:.3f}" if t in base else "-" for t in ("t1", "t2", "t3")]]
        rows += [[v["name"]] + [f"{v[t]['ndcg@10']:.3f}" if t in v else "-" for t in ("t1", "t2", "t3")]
                 for v in ab["hgt_variants"].values()]
        out += ["### Ablation: HGT structure (NDCG@10)", "", table(["Variant", "T1", "T2", "T3"], rows), ""]
    return "\n".join(out)


